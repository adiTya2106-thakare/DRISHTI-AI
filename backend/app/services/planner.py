# Drishti AI – Planner Service
# Tiered planning: local deterministic → optional LLM
# The local planner works offline without any API key.

from __future__ import annotations
import os
import re
import uuid
from typing import List
import logging

from app.models.schemas import PlanRequest, PlanResponse, AgentAction

logger = logging.getLogger("drishti.planner")

# ─── Planner Entry Point ──────────────────────────────────────────────────────

async def get_plan(request: PlanRequest) -> PlanResponse:
    """
    Returns a validated structured action plan.
    Uses the LLM planner if configured; otherwise falls back to local deterministic.
    """
    # Check for LLM configuration
    openai_key = os.environ.get("OPENAI_API_KEY", "").strip()
    anthropic_key = os.environ.get("ANTHROPIC_API_KEY", "").strip()

    if openai_key:
        try:
            return await get_openai_plan(request, openai_key)
        except Exception as e:
            logger.warning(f"OpenAI planner failed, using local: {e}")

    if anthropic_key:
        try:
            return await get_anthropic_plan(request, anthropic_key)
        except Exception as e:
            logger.warning(f"Anthropic planner failed, using local: {e}")

    return get_local_plan(request)

# ─── Local Deterministic Planner ─────────────────────────────────────────────

STOP_WORDS = {
    "the", "a", "an", "is", "in", "on", "and", "or", "for",
    "to", "of", "find", "search", "this", "page", "me", "i"
}

def extract_keywords(text: str) -> List[str]:
    words = re.sub(r"[^a-z0-9 ]", " ", text.lower()).split()
    return [w for w in words if len(w) > 3 and w not in STOP_WORDS]

def get_local_plan(request: PlanRequest) -> PlanResponse:
    task = request.taskText.lower()
    elements = request.sanitizedContext.sanitizedElements
    keywords = extract_keywords(request.taskText)

    steps: List[AgentAction] = []
    warnings: List[str] = []

    # Always start with inspection
    steps.append(AgentAction(type="INSPECT", reason="Inspect current page state"))

    # Find matching elements
    matched_elements = [
        el for el in elements
        if any(kw in el.label.lower() for kw in keywords)
        and not el.isSensitiveRedacted
    ]

    # Scroll if page is likely long
    if any(word in task for word in ["scroll", "bottom", "down", "more", "continue"]):
        steps.append(AgentAction(
            type="SCROLL",
            direction="down",
            pixels=400,
            reason="Scroll to reveal more content",
        ))

    # Click on matching interactive elements
    if any(word in task for word in ["click", "open", "visit", "go", "navigate", "follow", "link"]):
        for el in matched_elements[:2]:
            if el.isInteractive:
                steps.append(AgentAction(
                    type="CLICK",
                    elementId=el.id,
                    reason=f"Click: {el.label[:60]}",
                ))

    # Find and report content
    if any(word in task for word in ["find", "locate", "identify", "search", "where", "what", "when", "deadline", "date"]):
        if matched_elements:
            steps.append(AgentAction(
                type="ASK_USER",
                message=f"I found {len(matched_elements)} relevant element(s): "
                       + ", ".join(el.label[:40] for el in matched_elements[:3]),
            ))
        else:
            steps.append(AgentAction(
                type="ASK_USER",
                message="I could not find a specific match for your query. Check the highlighted elements in the overlay.",
            ))
            warnings.append("No exact element match found for the task keywords.")

    # Type / fill forms
    if any(word in task for word in ["fill", "enter", "type", "input", "write"]):
        form_elements = [el for el in elements if el.type in ("input", "textarea") and not el.isSensitiveRedacted]
        for el in form_elements[:2]:
            steps.append(AgentAction(
                type="TYPE",
                elementId=el.id,
                value="",
                reason=f"Fill field: {el.label[:40]}",
                requiresConfirmation=True,
            ))

    # Navigate
    if any(word in task for word in ["navigate", "go to", "open url"]):
        warnings.append("Navigation requires explicit URL and user confirmation.")
        steps.append(AgentAction(
            type="ASK_USER",
            message="Please provide the URL to navigate to.",
        ))

    # Always end with DONE
    steps.append(AgentAction(
        type="DONE",
        reason="Local planner analysis complete. Review highlighted elements and the Privacy Proof Ledger.",
    ))

    warnings.append("This plan was generated by the local deterministic planner (offline mode). For more accurate planning, configure an LLM in the backend.")

    return PlanResponse(
        planId=str(uuid.uuid4()),
        steps=steps,
        plannerUsed="local_deterministic_v1",
        warnings=warnings,
    )

# ─── OpenAI Planner ───────────────────────────────────────────────────────────

async def get_openai_plan(request: PlanRequest, api_key: str) -> PlanResponse:
    """
    Optional OpenAI-backed planner. Only called if OPENAI_API_KEY is set.
    Sends ONLY the sanitized context — never raw page data.
    """
    import httpx

    system_prompt = (
        "You are a browser agent planner. You receive a sanitized webpage context "
        "(all PII has been redacted) and a user task. Respond ONLY with a JSON array of actions.\n"
        "Each action has: type (one of INSPECT/CLICK/TYPE/SELECT/SCROLL/NAVIGATE/WAIT/ASK_USER/DONE), "
        "elementId (optional), selector (optional), value (optional), url (optional), "
        "direction (up/down/left/right), pixels (int), message (str), reason (str), requiresConfirmation (bool).\n"
        "Rules:\n"
        "- NEVER suggest typing into password or sensitive fields.\n"
        "- NEVER use javascript: URLs.\n"
        "- NAVIGATE always requires requiresConfirmation: true.\n"
        "- Form submissions require requiresConfirmation: true.\n"
        "- End every plan with a DONE action.\n"
        "- Return valid JSON only. No markdown, no explanation."
    )

    # Build a minimal, sanitized prompt
    context_summary = (
        f"Page URL: {request.pageUrl}\n"
        f"Task: {request.taskText}\n"
        f"Sanitized text (first 2000 chars):\n{request.sanitizedContext.sanitizedText[:2000]}\n"
        f"Elements ({len(request.sanitizedContext.sanitizedElements)}):\n"
        + "\n".join(
            f"  - id:{el.id} type:{el.type} label:{el.label} interactive:{el.isInteractive}"
            for el in request.sanitizedContext.sanitizedElements[:30]
        )
    )

    async with httpx.AsyncClient(timeout=15.0) as client:
        response = await client.post(
            "https://api.openai.com/v1/chat/completions",
            headers={"Authorization": f"Bearer {api_key}", "Content-Type": "application/json"},
            json={
                "model": "gpt-4o-mini",
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": context_summary},
                ],
                "max_tokens": 1000,
                "temperature": 0.2,
            },
        )
        response.raise_for_status()
        data = response.json()

    raw_steps = data["choices"][0]["message"]["content"].strip()

    # Parse and validate
    import json
    steps_data = json.loads(raw_steps)
    if not isinstance(steps_data, list):
        raise ValueError("LLM did not return a list of actions")

    steps = [AgentAction(**step) for step in steps_data]  # Pydantic validates each

    return PlanResponse(
        planId=str(uuid.uuid4()),
        steps=steps,
        plannerUsed="openai/gpt-4o-mini",
        warnings=["Plan generated by external LLM. Always review before confirming consequential actions."],
    )

# ─── Anthropic Planner ────────────────────────────────────────────────────────

async def get_anthropic_plan(request: PlanRequest, api_key: str) -> PlanResponse:
    """
    Optional Anthropic-backed planner. Only called if ANTHROPIC_API_KEY is set.
    """
    import httpx
    import json

    prompt = (
        "You are a browser agent planner. Return ONLY a JSON array of actions (no markdown).\n"
        "Action schema: {type, elementId?, selector?, value?, url?, direction?, pixels?, message?, reason?, requiresConfirmation?}\n"
        "Valid types: INSPECT CLICK TYPE SELECT SCROLL NAVIGATE WAIT ASK_USER DONE\n"
        "Rules: Never touch password fields. NAVIGATE needs requiresConfirmation:true. End with DONE.\n\n"
        f"Task: {request.taskText}\n"
        f"Page: {request.pageUrl}\n"
        f"Context: {request.sanitizedContext.sanitizedText[:2000]}\n"
        f"Elements: {json.dumps([{'id': el.id, 'type': el.type, 'label': el.label, 'interactive': el.isInteractive} for el in request.sanitizedContext.sanitizedElements[:30]])}"
    )

    async with httpx.AsyncClient(timeout=15.0) as client:
        response = await client.post(
            "https://api.anthropic.com/v1/messages",
            headers={
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
                "Content-Type": "application/json",
            },
            json={
                "model": "claude-3-haiku-20240307",
                "max_tokens": 1000,
                "messages": [{"role": "user", "content": prompt}],
            },
        )
        response.raise_for_status()
        data = response.json()

    raw_steps = data["content"][0]["text"].strip()
    steps_data = json.loads(raw_steps)
    steps = [AgentAction(**step) for step in steps_data]

    return PlanResponse(
        planId=str(uuid.uuid4()),
        steps=steps,
        plannerUsed="anthropic/claude-3-haiku",
        warnings=["Plan generated by external LLM. Always review before confirming consequential actions."],
    )
